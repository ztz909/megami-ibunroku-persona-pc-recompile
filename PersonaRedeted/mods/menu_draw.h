static void menu_fill(uint32_t* px, int x0, int y0, int w, int h, uint32_t c) {
    for (int y = y0 < 0 ? 0 : y0; y < y0 + h && y < MENU_H; y++)
        for (int x = x0 < 0 ? 0 : x0; x < x0 + w && x < MENU_W; x++)
            px[y * MENU_W + x] = c;
}

static void menu_text(uint32_t* px, int x, int y, const char* s, uint32_t col) {
    for (; *s && x < MENU_W - MENU_CH; s++, x += MENU_CH) {
        char c = *s;
        if (c >= 'a' && c <= 'z') c = (char)(c - 32);
        if (c < 32 || c > 90) c = '?';
        const uint8_t* g = MENU_FONT8[c - 32];
        for (int gy = 0; gy < 8; gy++)
            for (int gx = 0; gx < 8; gx++)
                if (g[gy] & (1u << gx))
                    menu_fill(px, x + gx * MENU_SCALE, y + gy * MENU_SCALE, MENU_SCALE, MENU_SCALE, col);
    }
}
